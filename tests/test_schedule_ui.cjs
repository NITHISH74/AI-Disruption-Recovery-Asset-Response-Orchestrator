// Focused test of schedule pagination with a minimal DOM stub. Run: node tests/test_schedule_ui.cjs
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('static/app.js', 'utf8');
const start = source.indexOf('let schedulePage=0;');
const end = source.indexOf('\nfunction render(){', start);
assert(start >= 0 && end > start, 'schedule renderer not found');
const elements = Object.fromEntries(['schedule-body','schedule-total','schedule-range','schedule-prev','schedule-next'].map(id => [id, {}]));
const ctx = {schedule: [], $: selector => elements[selector.slice(1)], esc: s => String(s).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]))};
vm.createContext(ctx);
vm.runInContext(source.slice(start,end),ctx);
vm.runInContext('renderSchedule()',ctx);
assert.equal(elements['schedule-range'].textContent,'No services');
assert.equal(elements['schedule-next'].disabled,true);
ctx.schedule = Array.from({length: 23}, (_,n) => ({id:`SERVICE-${String(n).padStart(2,'0')}`,origin:'BLR',destination:'DEL',departure:'2026-11-27T10:00:00Z',mode:'flight',status:'scheduled'}));
vm.runInContext('renderSchedule()',ctx);
assert.equal(elements['schedule-total'].textContent,'23 SERVICES');
assert.equal(elements['schedule-range'].textContent,'Showing 1–10 of 23');
assert.equal(elements['schedule-prev'].disabled,true);
elements['schedule-next'].onclick();
assert.equal(elements['schedule-range'].textContent,'Showing 11–20 of 23');
assert.match(elements['schedule-body'].innerHTML,/SERVICE-10/);
elements['schedule-next'].onclick();
assert.equal(elements['schedule-range'].textContent,'Showing 21–23 of 23');
assert.equal(elements['schedule-next'].disabled,true);
elements['schedule-prev'].onclick();
assert.equal(elements['schedule-range'].textContent,'Showing 11–20 of 23');
ctx.schedule = [{id:'<unsafe>',origin:'BLR',destination:'DEL',departure:'2026-11-27T10:00:00Z',mode:'flight',status:'canceled'}];
vm.runInContext('renderSchedule()',ctx);
assert.equal(elements['schedule-range'].textContent,'Showing 1–1 of 1');
assert.match(elements['schedule-body'].innerHTML,/&lt;unsafe&gt;/);
assert.match(elements['schedule-body'].innerHTML,/canceled/);
console.log('Schedule pagination, bounds, escaping, and status: passed');
